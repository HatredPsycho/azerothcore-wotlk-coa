    local cell = CreateFrame("Button", name, parent)
    cell:SetSize(CELL_SIZE, CELL_SIZE)
    cell:SetFrameStrata("MEDIUM")

    -- Icon
    local iconTex = cell:CreateTexture(nil, "ARTWORK")
