local function GetProfessionCategory(entry, itemType, itemSubType, itemName)
    if itemType == "Gem" then return "Jewelcrafting" end
    if itemType ~= "Trade Goods" then return "Other" end

    local recipeCategory = entry and ABYSSAL_RECIPE_CATEGORIES[entry]
    if recipeCategory then return recipeCategory end

    itemSubType = itemSubType or ""
    if itemSubType == "Cloth" then return "Tailoring" end
    if itemSubType == "Leather" then return "Leatherworking" end
    if itemSubType == "Metal & Stone" then return "Blacksmithing" end
    if itemSubType == "Herb" then return "Alchemy" end
    if itemSubType == "Elemental" then return "Other" end
    if itemSubType == "Enchanting" then return "Enchanting" end
    if itemSubType == "Jewelcrafting" then return "Jewelcrafting" end
    if itemSubType == "Cooking" or itemSubType == "Meat" then return "Cooking" end
    if itemSubType == "Parts" or itemSubType == "Explosives" or itemSubType == "Devices" then
        return "Engineering"
    end
    if itemSubType == "Armor Enchantment" or itemSubType == "Weapon Enchantment"
        or itemSubType == "Armor Vellum" or itemSubType == "Weapon Vellum" then
        return "Enchanting"
    end
    if itemName then
        local lowerName = itemName:lower()
        if lowerName:find("vellum", 1, true) then return "Enchanting" end
        if lowerName:find("pigment", 1, true) or lowerName:find("parchment", 1, true)
            or lowerName:find("%f[%a]ink%f[%A]") then
            return "Inscription"
        end
    end
    return "Other"
end

local itemMetaCache = {}

-- Only cache resolved items so uncached entries retry on the next rebuild
local function GetItemMeta(entry)
    local meta = itemMetaCache[entry]
    if meta then
        return meta.name, meta.itemType, meta.itemSubType, meta.icon
    end
    local name, _, _, _, _, itemType, itemSubType, _, _, icon = GetItemInfo(entry)
    if not name then return nil end
    meta = { name = name, itemType = itemType, itemSubType = itemSubType, icon = icon }
    itemMetaCache[entry] = meta
    return name, itemType, itemSubType, icon
end

local function BuildDisplayList()
    wipe(displayList)
    for entry, count in pairs(AbyssalStoragePlus.items) do
        local name, itemType, itemSubType, icon = GetItemMeta(entry)
        local category = GetItemCategory(itemType, itemSubType)
        local categoryMatches = selectedCategory == "All" or category == selectedCategory
        if name then
            if categoryMatches and (searchFilter == "" or name:lower():find(searchFilter:lower(), 1, true)) then
                table.insert(displayList, { entry = entry, count = count, name = name, icon = icon })
            end
        else
            -- Item not in client cache yet, show entry ID
            if categoryMatches and searchFilter == "" then
                table.insert(displayList, { entry = entry, count = count, name = "Item #" .. entry, icon = "Interface\\Icons\\INV_Misc_QuestionMark" })
            end
        end
    end
    table.sort(displayList, function(a, b) return a.name < b.name end)
end

